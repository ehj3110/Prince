def create_master_plot_with_mean(df, output_dir):
    """
    Create a master plot with 4 subplots using mean aggregation
    
    Args:
        df: DataFrame with all data
        output_dir: Directory to save plots
    """
    print(f"\n{'='*80}")
    print(f"Creating Master Plot with MEAN (4 subplots)")
    print(f"{'='*80}")
    
    # Define color map for conditions
    conditions = sorted(df['condition_label'].unique())
    colors = plt.cm.tab10(np.linspace(0, 1, len(conditions)))
    color_map = dict(zip(conditions, colors))
    
    # Metrics to plot (4 subplots)
    metrics = [
        ('Peak_Force_N', 'Peak Force (N)'),
        ('Work_of_Adhesion_mJ', 'Work of Adhesion (mJ)'),
        ('Total_Peel_Distance_mm', 'Total Peel Distance (mm)'),
        ('Distance_to_Peak_mm', 'Distance to Peak (mm)')
    ]
    
    # Create figure with 2x2 subplots
    fig, axes = plt.subplots(2, 2, figsize=(20, 16))
    axes = axes.flatten()
    
    for idx, (metric_col, ylabel) in enumerate(metrics):
        ax = axes[idx]
        
        for condition in conditions:
            condition_data = df[df['condition_label'] == condition]
            
            # Group by source_file (each autolog file)
            # All layers in the same file should have the same area
            file_groups = condition_data.groupby('source_file')
            
            radius_bins = []
            mean_values = []
            sem_values = []
            
            for file_name, file_data in file_groups:
                # Get mean area for this file (should all be the same)
                mean_area = file_data['Cross_Sectional_Area_mm2'].mean()
                
                # Get mean metric value for this file
                metric_data = file_data[metric_col].dropna()
                
                if len(metric_data) > 0:
                    radius_bins.append(np.sqrt(mean_area / np.pi))
                    mean_values.append(metric_data.mean())
                    sem_values.append(metric_data.sem())
            
            # Sort by radius for proper plotting
            sort_idx = np.argsort(radius_bins)
            radius_bins = np.array(radius_bins)[sort_idx]
            mean_values = np.array(mean_values)[sort_idx]
            sem_values = np.array(sem_values)[sort_idx]
            
            # Plot shaded error region (z-order=1)
            ax.fill_between(radius_bins, 
                           mean_values - sem_values,
                           mean_values + sem_values,
                           color=color_map[condition], alpha=0.2, zorder=1)
            
            # Fit power law and plot trendline (z-order=2)
            A, n, r_sq = fit_power_law(radius_bins, mean_values)
            if A is not None:
                x_smooth = np.linspace(radius_bins.min(), radius_bins.max(), 100)
                y_smooth = power_law(x_smooth, A, n)
                ax.plot(x_smooth, y_smooth, ':', linewidth=2, 
                       color=color_map[condition], zorder=2,
                       label=f'{condition} (n={n:.2f}, R²={r_sq:.3f})')
            
            # Plot data points (z-order=3)
            ax.scatter(radius_bins, mean_values, 
                      s=16, color=color_map[condition], zorder=3,
                      edgecolors='white', linewidth=0.5)
        
        # Format subplot
        ax.set_xlabel('Contact Radius (mm)', fontsize=12, fontweight='bold')
        ax.set_ylabel(ylabel, fontsize=12, fontweight='bold')
        ax.set_title(f'{ylabel} vs Contact Radius (MEAN)', 
                    fontsize=14, fontweight='bold')
        ax.legend(fontsize=9, loc='best')
        ax.grid(True, alpha=0.3)
        
        # Set y-axis to start at 0 if all values are positive
        if df[metric_col].min() >= 0:
            ax.set_ylim(bottom=0)
    
    # Save plot
    plot_path = output_dir / "automated_work_mean.png"
    plt.tight_layout()
    plt.savefig(plot_path, dpi=300, bbox_inches='tight')
    plt.close()
    
    print(f"  Saved: {plot_path.name}")


