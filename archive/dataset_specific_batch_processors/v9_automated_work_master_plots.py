def parse_v9_folder_name(folder_name):
    """Parse V9 folder name to extract parameters"""
    parts = folder_name.split('_')
    
    # Handle simple folder names (e.g., "FEP", "Hybrid - Compliant")
    if len(parts) <= 3:
        return {
            'membrane': folder_name,
            'gap_mm': 0.0,
            'tank': 'Unknown',
            'fluid': 'Unknown',
            'speed_um_s': None,
            'condition_label': folder_name
        }
    
    # Handle V9 format (Membrane_Gap_Tank_Fluid_Speed)
    membrane = parts[0]
    gap_mm = float(parts[1].replace('um', '')) / 1000
    tank = parts[2]
    fluid = parts[3]
    speed_um_s = int(parts[4]) if len(parts) > 4 else None
    
    condition_label = f"{membrane}_{int(gap_mm*1000)}um_{tank}_{fluid}_{speed_um_s}"
    
    return {
        'membrane': membrane,
        'gap_mm': gap_mm,
        'tank': tank,
        'fluid': fluid,
        'speed_um_s': speed_um_s,
        'condition_label': condition_label
    }


def power_law(x, A, n):
    """Power law function: y = A * x^n"""
    return A * np.power(x, n)


def fit_power_law(x_data, y_data):
    """
    Fit power law to data
    
    Returns:
        tuple: (A, n, r_squared) or (None, None, None) if fit fails
    """
    try:
        # Remove any NaN or inf values
        mask = np.isfinite(x_data) & np.isfinite(y_data) & (x_data > 0) & (y_data > 0)
        x_clean = x_data[mask]
        y_clean = y_data[mask]
        
        if len(x_clean) < 3:
            return None, None, None
        
        # Fit power law
        popt, _ = curve_fit(power_law, x_clean, y_clean, p0=[1, 1], maxfev=10000)
        A, n = popt
        
        # Calculate R²
        y_pred = power_law(x_clean, A, n)
        ss_res = np.sum((y_clean - y_pred) ** 2)
        ss_tot = np.sum((y_clean - np.mean(y_clean)) ** 2)
        r_squared = 1 - (ss_res / ss_tot)
        
        return A, n, r_squared
    except Exception as e:
        print(f"    Warning: Power law fit failed - {e}")
        return None, None, None


def load_all_automated_work_files():
    """Load data from MASTER_all_metrics.csv generated by batch processor"""
    v9_dir = Path(r"C:\Users\ehunt\OneDrive - Northwestern University\Lab Work\Nissan\Adhesion Tests\SteppedConeTests\V9_New")
    
    # Load from MASTER_all_metrics.csv
    master_csv = v9_dir / "data" / "MASTER_all_metrics.csv"
    
    if not master_csv.exists():
        raise FileNotFoundError(f"MASTER_all_metrics.csv not found at {master_csv}")
    
    print(f"Loading data from {master_csv}...")
    df = pd.read_csv(master_csv)
    
    # Rename columns to match expected format
    column_mapping = {
        'peak_force_N': 'Peak_Force_N',
        'work_of_adhesion_mJ': 'Work_of_Adhesion_mJ',
        'peel_distance_mm': 'Total_Peel_Distance_mm',
        'distance_to_peak_mm': 'Distance_to_Peak_mm',
        'area_mm2': 'Cross_Sectional_Area_mm2'
    }
    df.rename(columns=column_mapping, inplace=True)
    
    # Calculate radius
    df['radius_mm'] = np.sqrt(df['Cross_Sectional_Area_mm2'] / np.pi)
    
    print(f"Loaded {len(df)} layers")
    
    # Filter out priming layers (all layers with same area as first layer)
    min_area = df['Cross_Sectional_Area_mm2'].min()
    priming_layers = (df['Cross_Sectional_Area_mm2'] == min_area).sum()
    
    print(f"Filtering out {priming_layers} priming layers (area = {min_area:.4f} mm²)")
    df = df[df['Cross_Sectional_Area_mm2'] > min_area].copy()
    
    print(f"Total layers after filtering: {len(df)}")
    
    return df


