def create_comparison_plot(df, output_dir):
    """Create comparison plot with 4 subplots showing mean vs median"""
    print(f"\n{'='*80}")
    print(f"Creating Mean vs Median Comparison (4 subplots)")
    print(f"{'='*80}")
    
    conditions = sorted(df['condition_label'].unique())
    colors = plt.cm.tab10(np.linspace(0, 1, len(conditions)))
    color_map = dict(zip(conditions, colors))
    
    # Metrics to plot (4 subplots)
    metrics = [
        ('Peak_Force_N', 'Peak Force (N)'),
        ('Work_of_Adhesion_mJ', 'Work of Adhesion (mJ)'),
        ('Total_Peel_Distance_mm', 'Total Peel Distance (mm)'),
        ('Distance_to_Peak_mm', 'Distance to Peak (mm)')
    ]
    
    # Create figure with 2x2 subplots
    fig, axes = plt.subplots(2, 2, figsize=(24, 16))
    axes = axes.flatten()
    
    for idx, (metric_col, ylabel) in enumerate(metrics):
        ax = axes[idx]
        
        for condition in conditions:
            condition_data = df[df['condition_label'] == condition]
            
            # Bin by area
            unique_areas = sorted(condition_data['Cross_Sectional_Area_mm2'].unique())
            
            mean_areas = []
            mean_values = []
            mean_errors = []
            
            median_areas = []
            median_values = []
            median_errors = []
            
            for area in unique_areas:
                tolerance = 0.05
                mask = (condition_data['Cross_Sectional_Area_mm2'] >= area * (1 - tolerance)) & \
                       (condition_data['Cross_Sectional_Area_mm2'] <= area * (1 + tolerance))
                bin_data = condition_data[mask][metric_col].dropna()
                
                if len(bin_data) > 0:
                    # Mean
                    mean_areas.append(area)
                    mean_values.append(bin_data.mean())
                    mean_errors.append(bin_data.sem())
                    
                    # Median
                    median_areas.append(area)
                    median_values.append(bin_data.median())
                    mad = np.median(np.abs(bin_data - bin_data.median()))
                    median_errors.append(1.4826 * mad / np.sqrt(len(bin_data)))
            
            # Convert to radius and numpy arrays
            mean_radius = np.array([np.sqrt(a / np.pi) for a in mean_areas])
            mean_values = np.array(mean_values)
            mean_errors = np.array(mean_errors)
            
            median_radius = np.array([np.sqrt(a / np.pi) for a in median_areas])
            median_values = np.array(median_values)
            median_errors = np.array(median_errors)
            
            # ===== MEAN PLOTTING =====
            # 1. Shaded error region for mean (SEM)
            ax.fill_between(mean_radius,
                           mean_values - mean_errors,
                           mean_values + mean_errors,
                           color=color_map[condition], alpha=0.2, zorder=1)
            
            # 2. Power law trendline for mean
            A_mean, n_mean, r2_mean = fit_power_law(mean_radius, mean_values)
            if A_mean is not None:
                x_smooth = np.linspace(mean_radius.min(), mean_radius.max(), 100)
                y_smooth = power_law(x_smooth, A_mean, n_mean)
                ax.plot(x_smooth, y_smooth, ':', linewidth=2,
                       color=color_map[condition], zorder=2)
            
            # 3. Data points for mean (circles)
            ax.scatter(mean_radius, mean_values,
                      s=16, marker='o', color=color_map[condition], zorder=3,
                      edgecolors='white', linewidth=0.5,
                      label=f'{condition} Mean (n={n_mean:.2f}, R²={r2_mean:.3f})' if A_mean is not None else f'{condition} Mean')
            
            # ===== MEDIAN PLOTTING =====
            # 1. Shaded error region for median (MAD-based)
            ax.fill_between(median_radius,
                           median_values - median_errors,
                           median_values + median_errors,
                           color=color_map[condition], alpha=0.15, zorder=1)
            
            # 2. Power law trendline for median (dashed)
            A_med, n_med, r2_med = fit_power_law(median_radius, median_values)
            if A_med is not None:
                x_smooth = np.linspace(median_radius.min(), median_radius.max(), 100)
                y_smooth = power_law(x_smooth, A_med, n_med)
                ax.plot(x_smooth, y_smooth, '--', linewidth=2,
                       color=color_map[condition], zorder=2)
            
            # 3. Data points for median (squares)
            ax.scatter(median_radius, median_values,
                      s=16, marker='s', color=color_map[condition], zorder=3,
                      edgecolors='white', linewidth=0.5,
                      label=f'{condition} Median (n={n_med:.2f}, R²={r2_med:.3f})' if A_med is not None else f'{condition} Median')
        
        # Format subplot
        ax.set_xlabel('Contact Radius (mm)', fontsize=12, fontweight='bold')
        ax.set_ylabel(ylabel, fontsize=12, fontweight='bold')
        ax.set_title(f'{ylabel}: Mean vs Median', 
                    fontsize=14, fontweight='bold')
        ax.legend(fontsize=9, loc='best', ncol=1)
        ax.grid(True, alpha=0.3)
        
        if df[metric_col].min() >= 0:
            ax.set_ylim(bottom=0)
    
    # Save plot
    plot_path = output_dir / "automated_work_mean_vs_median_comparison.png"
    plt.tight_layout()
    plt.savefig(plot_path, dpi=300, bbox_inches='tight')
    plt.close()
    
    print(f"  Saved: {plot_path.name}")


